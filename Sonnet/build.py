#!/usr/bin/env python3
"""Builds the Sonnet Arcade card scripts from src/*.part.
  Vibecode3D_Play_SonnetArcade.livecodescript   the launcher: menu + all five games
  Vibecode3D_Play_Sonnet<Name>.livecodescript   each game alone (no menu)
Run:  python3 -I build.py            (writes into ./cards/)"""
import os, sys, datetime
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'src')
OUT = os.path.join(HERE, 'cards')

GAMES = [  # file, prefix, card name, one line
    ('g01_rain.part', 'Rain', 'SonnetRain', 'NONSENSE RAIN: catch valid code, dodge the Cone\'s nonsense'),
    ('g02_password.part', 'Password', 'SonnetPassword', 'THE PASSWORD: Mastermind against the Cone, Glaze can barter'),
    ('g03_glaze.part', 'Glaze', 'SonnetGlaze', 'GLAZE OVER: a charm ring, risk against reward'),
    ('g04_runtime.part', 'Runtime', 'SonnetRuntime', 'RUNAWAY RUNTIME: two copies, one brain, five rooms'),
    ('g05_squad.part', 'Squad', 'SonnetSquad', 'SQUAD SHUFFLE: rearrange three soldiers before the gate lands'),
]

def read(n):
    return open(os.path.join(SRC, n), encoding='utf-8').read().rstrip('\n') + '\n'

def runtime_rows():
    levels = open(os.path.join(HERE, 'tests', 'runtime_levels.txt')).read().strip().split('\n\n')
    out = ['function Runtime.Rows pLevel', '   switch pLevel']
    for i, lv in enumerate(levels, 1):
        rows = [r for r in lv.split('\n') if r.strip()]
        out.append('      case %d' % i)
        out.append('         return ' + ' & cr & '.join('"%s"' % r for r in rows))
    out += ['   end switch', '   return empty', 'end Runtime.Rows']
    return '\n'.join(out)

def module(name):
    t = read(name)
    return t.replace('@@RUNTIME_ROWS@@', runtime_rows())

def header(title, lines):
    stamp = datetime.date.today().strftime('%m %d %Y')
    h = ['#' * 86, '## CARD SCRIPT: "Play.%s"   (%s)' % (title, stamp),
         '## Written by Sonnet 5.5. Generated by Sonnet/build.py from Sonnet/src: edit the .part files, not this.',
         '## Engine contract only (LIB_ig3d/ENGINE_CONTRACT.md); keyboard only; no mouse, no files.']
    h += ['## ' + l for l in lines]
    h.append('#' * 86)
    return '\n'.join(h) + '\n\n'

def main():
    os.makedirs(OUT, exist_ok=True)
    core = read('00_core.part')
    arcade = header('SonnetArcade', ['THE SONNET ARCADE: a launcher card with five games inside it.',
                    'UP DOWN SPACE or 1-5 pick; M returns to the menu; Escape pauses (the player).'] + [g[3] for g in GAMES])
    arcade += core
    for f, pre, name, line in GAMES:
        arcade += '\n' + module(f)
    arcade += '\n' + read('90_arcade.part')
    open(os.path.join(OUT, 'Vibecode3D_Play_SonnetArcade.livecodescript'), 'w', encoding='utf-8', newline='\n').write(arcade)
    for f, pre, name, line in GAMES:
        t = header(name, [line, 'M leaves the game; SPACE restarts it after a win or a loss.']) + core + '\n' + module(f) + '\n' + read('91_solo.part').replace('@@PRE@@', pre)
        open(os.path.join(OUT, 'Vibecode3D_Play_%s.livecodescript' % name), 'w', encoding='utf-8', newline='\n').write(t)
    print('built', len(GAMES) + 1, 'cards in', OUT)

main()
